import react from '@vitejs/plugin-react'
import { defineConfig } from 'vite'

/* Прокси для разработки.
 *
 * На проде nginx отдаёт статику и проксирует /api на бэкенд, поэтому
 * фронт ходит на тот же origin и VITE_API_BASE пуст. В разработке фронт
 * живёт на 5173, а API на 8000, и без прокси запрос на /api/calc уходил
 * на сам Vite — тот отвечал 404, и расчёт по своему контуру падал с
 * «Запрос отклонён (404)».
 *
 * Раньше это лечилось инструкцией «скопируйте .env.example в
 * .env.development». Инструкцию никто не выполняет, и ветка «задать свой
 * контур» оказывалась сломанной у каждого, кто просто запустил npm run
 * dev. Прокси делает то же самое, но без ручного шага.
 *
 * VITE_API_BASE по-прежнему работает и имеет приоритет: если он задан,
 * запросы идут по нему, минуя прокси.
 */
export default defineConfig({
  plugins: [react()],
  server: {
    proxy: {
      '/api': {
        target: 'http://127.0.0.1:8000',
        changeOrigin: true,
      },
    },
  },
})
