/* Новая страница открывается сверху.

   Браузер сохраняет прокрутку при смене адреса внутри приложения, и
   переход из середины длинного каталога на карточку участка открывал её
   где придётся — обычно посреди таблицы, без заголовка и без названия
   участка. Человек видел числа, не понимая, чьи они.

   Прокрутка сбрасывается только при смене пути. Смена параметров в
   адресе (выбор участков для сравнения, период) оставляет позицию на
   месте: это та же страница, и прыгать наверх при каждой галочке —
   отдельная беда. */

import { useEffect } from "react";
import { useLocation } from "react-router-dom";

export default function ScrollToTop() {
  const { pathname } = useLocation();

  useEffect(() => {
    window.scrollTo({ top: 0, left: 0, behavior: "auto" });
  }, [pathname]);

  return null;
}
